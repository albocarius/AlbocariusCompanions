    private static void RenderTrigger(TriggerDefinition t, System.Action<string> L)
    {
        L($"### {t.Name}");
        L("");
        L(t.Description);
        L("");
        L($"- Source: {(t.IsPolling ? "polling (internal tick)" : "`CampaignEvents." + t.Source + "`")}{(t.InMission ? " — fires in a battle or scene (in mission)" : "")}");
        var subjects = t.SubjectKinds().Select(k => Subjects.WithId.Contains(k) ? $"`{k}:<id>`" : $"`{k}`");
        L($"- Subjects: {string.Join(", ", subjects)}; default `{t.DefaultSubject}`{(t.SubjectFields.Count > 0 ? $" (matched on {string.Join(", ", t.SubjectFields.Select(f => "`" + f + "`"))})" : "")}");
        L("");
        if (t.Fields.Count > 0)
        {
            L("| Field | Kind | Meaning |");
            L("|---|---|---|");
            foreach (var f in t.Fields)
                L($"| `{f.Name}` | {f.Kind} | {Escape(f.Description)} |");
            L("");
        }
        if (t.Parameters.Count > 0)
        {
            L("| Parameter | Kind | Required | Meaning |");
            L("|---|---|---|---|");
            foreach (var p in t.Parameters)
                L($"| `{p.Name}` | {p.Kind} | {(p.Required ? "yes" : "no")} | {Escape(p.Description)} |");
            L("");
        }
        L("```json");
        L(Example(t));
        L("```");
        L("");
    }

    private static string Example(TriggerDefinition t)
    {
        var parts = new List<string> { $"\"on\": \"{t.Name}\"" };
        if (t.DefaultSubject != Subjects.Any)
            parts.Add($"\"subject\": \"{t.DefaultSubject}\"");
        var cultured = t.Fields.FirstOrDefault(f => EntityProperties.Of(f.Kind).Contains("culture"));
        if (cultured != null)
            parts.Add($"\"where\": {{ \"{cultured.Name}.culture\": \"vlandia\" }}");
        if (t.Parameters.Count > 0)
            parts.Add("\"params\": { " + string.Join(", ", t.Parameters.Select(p => $"\"{p.Name}\": {SampleValue(t, p)}")) + " }");
        return "\"trigger\": { " + string.Join(", ", parts) + " }";
    }

    private static string SampleValue(TriggerDefinition t, TriggerParameter p) => (t.Name, p.Name) switch
    {
        (_, "settlement") => "\"town_V1\"",
        (_, "radius") => "5",
        (_, "rearmRadius") => "8",
        (_, "var") => "\"mood\"",
        (_, "value") => "10",
        (_, "direction") => "\"up\"",
        (_, "role") => "\"governor\"",
        _ => p.Kind == FieldKind.Text ? "\"\"" : "0",
    };

    private static string Escape(string text) => text.Replace("|", "\\|");

    private static string Num(double value) => value.ToString(CultureInfo.InvariantCulture);
}
